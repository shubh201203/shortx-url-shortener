from fastapi import APIRouter, Request, HTTPException, Depends
from fastapi.responses import RedirectResponse
from datetime import datetime, timedelta

from ..models.schemas import URLCreate, URLResponse, AnalyticsResponse
from ..services.url_service import create_unique_short_code, predict_spam_status
from ..core.database import db
from ..core.redis import redis_client
from ..worker.analytics import analytics_queue
from ..core.rate_limiter import sliding_window_rate_limit

router = APIRouter()

@router.post("/api/shorten", response_model=URLResponse, dependencies=[Depends(sliding_window_rate_limit)])
async def create_short_url(payload: URLCreate, request: Request):
    """Creates a shortened URL and scores it using the ML spam model."""
    original_url = str(payload.url)
    
    # 1. Predict spam status
    status = predict_spam_status(original_url)
    
    # 2. Generate unique code
    short_code = await create_unique_short_code()
    
    now = datetime.utcnow()
    
    # 3. Create document
    url_doc = {
        "short_code": short_code,
        "original_url": original_url,
        "status": status,
        "created_at": now,
        "user_id": "anonymous" # MVP open dashboard
    }
    
    await db.db.urls.insert_one(url_doc)
    
    # 4. Return response
    return URLResponse(
        short_code=short_code,
        original_url=original_url,
        status=status,
        created_at=now
    )

@router.get("/r/{code}", dependencies=[Depends(sliding_window_rate_limit)])
async def redirect_url(code: str, request: Request):
    """Ultra fast redirect service using cache-aside pattern."""
    
    # 1. Check Cache
    cached_url = await redis_client.get(f"url:{code}")
    
    url = cached_url
    if not url:
        # 2. Cache miss, check DB
        url_doc = await db.db.urls.find_one({"short_code": code})
        if not url_doc:
            raise HTTPException(status_code=404, detail="URL not found")
        
        url = url_doc["original_url"]
        # 3. Update Cache (TTL 24 hours)
        await redis_client.setex(f"url:{code}", 86400, url)
    else:
        # Signal custom logging state for middleware
        request.state.cache_hit = True
    
    # 4. Offload analytics event to queue (non-blocking)
    analytics_event = {
        "short_code": code,
        "ip": request.client.host if request.client else None,
        "user_agent": request.headers.get("user-agent"),
    }
    await analytics_queue.put(analytics_event)
    
    return RedirectResponse(url=url)

@router.get("/api/analytics/summary")
async def get_analytics_summary():
    """Fetches global top stats for the dashboard homepage."""
    # Aggregate total global clicks over all short_codes
    pipeline = [
        {"$group": {"_id": None, "total_clicks": {"$sum": "$total_clicks"}}}
    ]
    cursor = db.db.analytics.aggregate(pipeline)
    res = await cursor.to_list(length=1)
    global_clicks = res[0]["total_clicks"] if res else 0

    total_links = await db.db.urls.count_documents({})

    top_links = await db.db.analytics.find().sort("total_clicks", -1).limit(5).to_list(length=5)
    
    top_formatted = []
    for link in top_links:
        short_code = link.get("short_code")
        url_doc = await db.db.urls.find_one({"short_code": short_code})
        top_formatted.append({
            "short_code": short_code,
            "original_url": url_doc["original_url"] if url_doc else "Unknown",
            "clicks": link.get("total_clicks", 0)
        })

    # Prepare chart data (last 7 days globally)
    now = datetime.utcnow()
    seven_days_ago = now - timedelta(days=7)
    
    chart_pipeline = [
        {"$match": {"timestamp": {"$gte": seven_days_ago}}},
        {
            "$group": {
                "_id": {"$dateToString": {"format": "%Y-%m-%d", "date": "$timestamp"}},
                "clicks": {"$sum": 1}
            }
        }
    ]
    
    chart_cursor = db.db.raw_clicks.aggregate(chart_pipeline)
    chart_data_raw = await chart_cursor.to_list(length=10)
    
    daily_clicks_map = {item["_id"]: item["clicks"] for item in chart_data_raw}
    
    chart_formatted = []
    for i in range(6, -1, -1):
        target_date_obj = now - timedelta(days=i)
        target_date_str = target_date_obj.strftime("%Y-%m-%d")
        chart_formatted.append({
            "name": target_date_obj.strftime("%a"),
            "fullDate": target_date_str,
            "clicks": daily_clicks_map.get(target_date_str, 0)
        })

    return {
        "global_clicks": global_clicks,
        "total_links": total_links,
        "top_links": top_formatted,
        "chart_data": chart_formatted
    }

@router.get("/api/analytics/{code}", response_model=AnalyticsResponse)
async def get_analytics(code: str):
    """Fetches fast aggregations generated by the async worker."""
    doc = await db.db.analytics.find_one({"short_code": code})
    if not doc:
        url_exists = await db.db.urls.find_one({"short_code": code})
        if not url_exists:
            raise HTTPException(status_code=404, detail="URL not found")
        return AnalyticsResponse(short_code=code, total_clicks=0, clicks_per_day={})
        
    return AnalyticsResponse(
        short_code=doc.get("short_code"),
        total_clicks=doc.get("total_clicks", 0),
        clicks_per_day=doc.get("clicks_per_day", {})
    )

@router.get("/api/metrics")
async def system_metrics():
    """System health metrics parsed directly from fast Redis counters."""
    pipe = redis_client.pipeline()
    pipe.get("metrics:total_redirects")
    pipe.get("metrics:cache_hits")
    pipe.get("metrics:cache_misses")
    pipe.get("metrics:rate_limited")
    results = await pipe.execute()
    
    return {
        "total_redirects": int(results[0]) if results[0] else 0,
        "cache_hits": int(results[1]) if results[1] else 0,
        "cache_misses": int(results[2]) if results[2] else 0,
        "rate_limited": int(results[3]) if results[3] else 0
    }
